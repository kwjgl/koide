  //  대림절(성탄 전 넷째 주일~12/24), 성탄절 12/25~12/31
  function seasonKey(day) {
    const y = day.getFullYear(), n = dayNo(day), at = (m, d) => dayNo(new Date(y, m - 1, d)), on = (a, b) => n >= a && n <= b, E = easterDay(y);
    const harvest = at(11, 1 + (7 - new Date(y, 10, 1).getDay()) % 7 + 14);
    const advent = at(12, 25) - (new Date(y, 11, 25).getDay() || 7) - 21;
    const k = on(at(1, 1), at(1, 7)) ? 'newyear' : on(E - 46, E - 1) ? 'lent' : on(E, E + 6) ? 'easter' : on(E + 49, E + 55) ? 'pentecost'
      : on(harvest - 6, harvest) ? 'harvest' : on(advent, at(12, 24)) ? 'advent' : on(at(12, 25), at(12, 31)) ? 'christmas' : '';
    return k;
  }
  return { LORDS_PRAYER, PRAY_TOPICS, PRAY_THANKS, PRAY_SEASONS, dayNo, seasonKey };
